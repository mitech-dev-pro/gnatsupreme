import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { prisma } from "../src/lib/prisma.js";

// Exports the live Region/District table and the staff-curated DistrictAlias rows (see
// src/modules/geography/geography.routes.ts's GET /districts/aliases and
// src/modules/geography/district-match.ts for how aliases are used during import) as plain
// JSON, plus a Python module with the same two names (GEOGRAPHY, ALIASES) that
// temp/match_districts.py already expects -- that file currently hardcodes both as a static
// snapshot, which drifts from the real DB (e.g. doesn't see any alias a staff member has since
// curated through the admin UI). Swapping match_districts.py's two literals for
// `from app_geography_live import GEOGRAPHY, ALIASES` closes that gap without changing its
// matching logic at all.
//
// Run with:
//   npx tsx scripts/export-live-geography.ts

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const OUTPUT_DIR = path.resolve(SCRIPT_DIR, "../../temp");

function pyStr(value: string): string {
  return `"${value.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
}

async function main() {
  const regions = await prisma.region.findMany({
    select: { id: true, name: true },
    orderBy: { name: "asc" },
  });
  const districts = await prisma.district.findMany({
    select: {
      id: true,
      name: true,
      region: { select: { name: true } },
      aliases: { select: { alias: true } },
    },
    orderBy: [{ region: { name: "asc" } }, { name: "asc" }],
  });

  const geography: Record<string, string[]> = {};
  for (const region of regions) geography[region.name] = [];
  for (const district of districts) {
    geography[district.region.name]!.push(district.name);
  }

  // DistrictAlias.alias is unique in the schema, so no two districts can ever claim the same
  // alias string -- no conflict handling needed here.
  const aliases: Record<string, string> = {};
  for (const district of districts) {
    for (const { alias } of district.aliases) aliases[alias] = district.name;
  }

  const json = {
    generatedAt: new Date().toISOString(),
    regions,
    geography,
    aliases,
    districts: districts.map((d) => ({
      id: d.id,
      name: d.name,
      region: d.region.name,
      aliases: d.aliases.map((a) => a.alias),
    })),
  };

  const jsonPath = path.join(OUTPUT_DIR, "app_geography_live.json");
  await writeFile(jsonPath, JSON.stringify(json, null, 2));

  const pyLines: string[] = [
    "# Auto-generated by backend/scripts/export-live-geography.ts -- do not edit by hand.",
    `# Generated ${json.generatedAt}`,
    "GEOGRAPHY = {",
  ];
  for (const region of regions) {
    const names = geography[region.name]!.map(pyStr).join(", ");
    pyLines.push(`    ${pyStr(region.name)}: [${names}],`);
  }
  pyLines.push("}", "", "ALIASES = {");
  for (const [alias, districtName] of Object.entries(aliases)) {
    pyLines.push(`    ${pyStr(alias)}: ${pyStr(districtName)},`);
  }
  pyLines.push("}", "");

  const pyPath = path.join(OUTPUT_DIR, "app_geography_live.py");
  await writeFile(pyPath, pyLines.join("\n"));

  console.log(
    `${regions.length} regions, ${districts.length} districts, ${Object.keys(aliases).length} aliases`,
  );
  console.log(`Wrote ${jsonPath}`);
  console.log(`Wrote ${pyPath}`);
  console.log(
    `\nTo use the live data in match_districts.py, replace its hardcoded GEOGRAPHY and\nRAW_ALIASES literals with:\n  from app_geography_live import GEOGRAPHY, ALIASES\n(and drop the RAW_ALIASES-to-ALIASES normalization loop, since ALIASES here is already\nkeyed by exact district name, not normalized -- or keep normalizing, it's idempotent.)`,
  );
}

main()
  .catch((error) => {
    console.error(error);
    process.exitCode = 1;
  })
  .finally(() => prisma.$disconnect());
